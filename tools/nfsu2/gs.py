def addr32(x, y, bw):
    """Word address of PSMCT32 pixel (x, y) in a buffer bw * 64 pixels wide."""
    return ((y // 32) * bw + x // 64) * 2048 + BLOCK32[(y % 32) // 8, (x % 64) // 8] * 64 + COLUMN32[y % 8, x % 8]


def addr16(x, y, bw):
    """Halfword address of PSMCT16 pixel (x, y)."""
    return ((y // 64) * bw + x // 64) * 4096 + BLOCK16[(y % 64) // 8, (x % 64) // 16] * 128 + COLUMN16[y % 8, x % 16]


def addr8(x, y, bw):
    """Byte address of PSMT8 pixel (x, y)."""
    return ((y // 64) * max(1, bw // 2) + x // 128) * 8192 + BLOCK8[(y % 64) // 16, (x % 128) // 16] * 256 + COLUMN8[y % 16, x % 16]


def addr4(x, y, bw):
    """Nibble address of PSMT4 pixel (x, y)."""
    return ((y // 128) * max(1, bw // 2) + x // 128) * 16384 + BLOCK4[(y % 128) // 16, (x % 128) // 32] * 512 + COLUMN4[y % 16, x % 32]


def write_read(data, wfmt, ww, wh, wbw, rfmt, w, h, rbw):
    """Writes data as a ww x wh rectangle of wfmt (32 or 16-bit) pixels, buffer width wbw, and
    reads a w x h rectangle of rfmt (8 or 4-bit) indices, buffer width rbw."""
    unit = {32: 4, 16: 2}[wfmt]
    y, x = np.mgrid[0:wh, 0:ww]
    a = {32: addr32, 16: addr16}[wfmt](x, y, wbw)
    raw = np.frombuffer(data, np.uint8, ww * wh * unit).reshape(-1, unit)
    mem = np.zeros((max(int(a.max()) + 1, 1 << 15), unit), np.uint8)
    mem[a.ravel()] = raw
    mem = mem.ravel()
    yy, xx = np.mgrid[0:h, 0:w]
    if rfmt == 8:
        return mem[np.minimum(addr8(xx, yy, rbw), mem.size - 1)]
    a4 = np.minimum(addr4(xx, yy, rbw), mem.size * 2 - 1)
    byte = mem[a4 >> 1]
    return np.where(a4 & 1, byte >> 4, byte & 15).astype(np.uint8)
